import type { GeneratedAttribute } from "./gitattributes.ts";
import { isLockfile } from "./lockfiles.ts";
import { basename } from "./path.ts";
import type { FileChange } from "./types.ts";

const MARKERS: readonly { readonly name: string; readonly pattern: RegExp }[] = [
  { name: "@generated", pattern: /@generated\b/ },
  { name: "Code generated … DO NOT EDIT.", pattern: /Code generated .+ DO NOT EDIT\./ },
  { name: "<auto-generated", pattern: /<auto-generated/ },
];

const MARKER_LINES = 5;

export interface GeneratedContext {
  readonly attributeFor: (path: string) => GeneratedAttribute | null;
  /** By the file's old path. undefined when not fetched, null when the file doesn't exist. */
  readonly baseContent: string | null | undefined;
  readonly headContent: string | null | undefined;
}

/**
 * Why a file is generated, or null. A renamed file must be generated under both names, so
 * renaming code to `yarn.lock` doesn't hide it.
 */
export const generatedReason = (file: FileChange, context: GeneratedContext): string | null => {
  const paths = file.oldPath === null ? [file.path] : [file.path, file.oldPath];

  if (paths.every(isLockfile)) return `lockfile (${basename(file.path)})`;

  const attributes = paths.map(context.attributeFor);
  const [attribute] = attributes;
  if (attribute && attributes.every((a) => a === attribute)) return `.gitattributes: ${attribute}`;

  // Both versions, so adding a marker in this PR can't hide the file.
  const marker = MARKERS.find(
    ({ pattern }) =>
      hasMarker(context.baseContent, pattern) && hasMarker(context.headContent, pattern),
  );
  return marker ? `marker "${marker.name}" in base and head` : null;
};

const hasMarker = (content: string | null | undefined, pattern: RegExp): boolean =>
  typeof content === "string" &&
  content.split("\n", MARKER_LINES).some((line) => pattern.test(line));
